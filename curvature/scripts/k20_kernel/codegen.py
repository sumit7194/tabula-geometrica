"""Generate mn_eval.c: the reduced MN Hamiltonian's vector field, its exact Jacobian (analytic Hessian of H), dt/dtau,
g_phiphi, the det-g sign factor and H itself, from one sympy expression (prereg A2.2). Parameters (alpha, k, beta, E, L)
are runtime arguments, so one compiled kernel serves every point and level (and Kerr: beta = 0)."""
import sys
import time
from pathlib import Path

import sympy as sp

x, y, px, py = sp.symbols("x y px py", real=True)
al, k, be, E, L = sp.symbols("al k be E L", real=True)

R2 = x**2 + y**2 - 1
R = sp.sqrt(R2)
mu = x * y / R
P = [sp.Integer(1), mu, (3 * mu**2 - 1) / 2, (5 * mu**3 - 3 * mu) / 2]
Rm = [1 / R, 1 / R**2, 1 / R**3]
psi = be * P[2] / R**3
S_a = sum((x - y) * P[l] * Rm[l] for l in range(3))
S_b = sum(((-1) ** (3 - l)) * (x + y) * P[l] * Rm[l] for l in range(3))
a = -al * sp.exp(-2 * be * (-1 + S_a))
b = al * sp.exp(2 * be * (1 + S_b))
S_g = sum((x - y + ((-1) ** (2 - l)) * (x + y)) * P[l] * Rm[l] for l in range(3))
G = sp.exp(3 * be**2 * R2**-3 * (P[3]**2 - P[2]**2) + 2 * be * (S_g - 2))
ab = a * b
A = (x**2 - 1) * (1 + ab)**2 - (1 - y**2) * (b - a)**2
B = (x + 1 + (x - 1) * ab)**2 + ((1 + y) * a + (1 - y) * b)**2
C = (x**2 - 1) * (1 + ab) * (b - a - y * (a + b)) + (1 - y**2) * (b - a) * (1 + ab + x * (1 - ab))
e2psi = sp.exp(2 * psi)
f = e2psi * A / B
w = 2 * k * sp.exp(-2 * psi) * C / A - 4 * k * al / (1 - al**2)
rho2 = k**2 * (x**2 - 1) * (1 - y**2)
pref = (1 - al**2)**2 * e2psi / (k**2 * B * G)
# Regularised at the ergosurface A = 0 (LGAC: "removing the zeros of A analytically"). Exact identity, verified by
# polynomial division with zero remainder (a, b as symbols): rho^2 B^2 - 4 k^2 C^2 = k^2 A Q.
aa, bb = sp.symbols("aa bb")
Q = ((x**2 - 1) * (1 - y**2) * ((x + 1 + (x - 1) * aa * bb)**2 + ((1 + y) * aa + (1 - y) * bb)**2)**2
     - 4 * ((x**2 - 1) * (1 + aa * bb) * (bb - aa - y * (aa + bb))
            + (1 - y**2) * (bb - aa) * (1 + aa * bb + x * (1 - aa * bb)))**2)
Q = sp.div(sp.Poly(sp.expand(Q), x, y, aa, bb),
           sp.Poly(sp.expand((x**2 - 1) * (1 + aa * bb)**2 - (1 - y**2) * (bb - aa)**2), x, y, aa, bb))
assert Q[1].is_zero
Q = Q[0].as_expr().subs({aa: a, bb: b})
w0 = 4 * k * al / (1 - al**2)
Lp = L + w0 * E
V = sp.Rational(1, 2) * (e2psi * A * Lp**2 - 4 * k * C * E * Lp - k**2 * E**2 * Q / e2psi) / (rho2 * B)
H = sp.Rational(1, 2) * pref * ((x**2 - 1) * px**2 + (1 - y**2) * py**2) + V

t0 = time.time()
Z = [x, y, px, py]
grad = [sp.diff(H, v) for v in Z]
rhs = [grad[2], grad[3], -grad[0], -grad[1]]
jac = [[sp.diff(r, v) for v in Z] for r in rhs]
tdot = -sp.diff(V, E)                                   # dt/dtau = dH/dp_t, with p_t = -E
gpp = (k**2 * Q / e2psi + 4 * k * w0 * C - e2psi * w0**2 * A) / B
outs = rhs + [jac[i][j] for i in range(4) for j in range(4)] + [tdot, gpp, pref, H, f, B]
print("differentiated in %.1fs" % (time.time() - t0), flush=True)
t0 = time.time()
rep, red = sp.cse(outs, optimizations="basic")
print("cse in %.1fs: %d subexpressions" % (time.time() - t0, len(rep)), flush=True)

lines = ["#include <math.h>",
         "/* generated by codegen.py -- do not edit. out[0..3] rhs, out[4..19] Jacobian (row-major d rhs_i / d z_j),",
         "   out[20] dt/dtau, out[21] g_phiphi, out[22] pref (det g < 0 iff pref > 0 and rho^2 > 0), out[23] H,",
         "   out[24] f, out[25] B. par = {al, k, be, E, L}. */",
         "void mn_eval(const double *par, const double *z, double *out) {",
         "  const double al = par[0], k = par[1], be = par[2], E = par[3], L = par[4];",
         "  const double x = z[0], y = z[1], px = z[2], py = z[3];"]
for s_, e_ in rep:
    lines.append("  const double %s = %s;" % (s_, sp.ccode(e_)))
for i, e_ in enumerate(red):
    lines.append("  out[%d] = %s;" % (i, sp.ccode(e_)))
lines.append("}")
Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
print("wrote", sys.argv[1], "lines", len(lines))
